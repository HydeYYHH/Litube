package com.hhst.youtubelite.extractor

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.Transient
import com.liskovsoft.youtubeapi.videoinfo.V2.PlayerTracking

@Serializable
data class Subtitle(
    val url: String = "",
    val languageCode: String = "",
    val autoGenerated: Boolean = false,
    val mimeType: String = "",
    @Transient val requestPlan: MediaRequestPlan? = null,
)

@Serializable
data class Format(
    val url: String = "",
    val height: Int = 0,
    val width: Int = 0,
    val bitrate: Int = 0,
    val fps: Int = 0,
    val qualityLabel: String? = null,
    val codec: String? = null,
    /** e.g. WEBM or MPEG_4. */
    @SerialName("format")
    val container: String? = null,
    val itag: Int? = null,
    val videoOnly: Boolean = false,
    val audioOnly: Boolean = false,
    /** e.g. "video/mp4", "audio/webm". */
    val mimeType: String = "",
    val initStart: Int = -1,
    val initEnd: Int = -1,
    val indexStart: Int = -1,
    val indexEnd: Int = -1,
    val approxDurationMs: Long = -1L,
    val sampleRate: Int = -1,
    val audioChannels: Int = -1,
    val audioLocale: String? = null,
    val audioTrackId: String? = null,
    val audioTrackName: String? = null,
    /** `original`, `dubbed`, `descriptive`, or `secondary`. */
    val audioTrackType: String? = null,
    val audioTrackOriginal: Boolean = false,
    /** Stable identity of the format, audio track and codec. */
    @SerialName("formatKey2")
    val formatKey: String? = null,
    val resourceIdentity: String? = null,
    val expiresAtMillis: Long? = null,
    @Transient val requestPlan: MediaRequestPlan? = null,
) {
    /**
     * Usable sidx range for synthetic DASH. `>= 0` alone would accept a missing
     * (0-defaulted) range and emit a broken `indexRange="0-0"`; `indexEnd > indexStart`
     * also rejects the 1-byte index the host does not emit.
     */
    val hasDashRanges: Boolean
        get() = initStart >= 0 && initEnd >= initStart && indexEnd > indexStart
}

@Serializable
data class Chapter(
    val title: String = "",
    val startSeconds: Int = 0,
    val previewUrl: String? = null,
)

@Serializable
class Metadata(
    var id: String = "",
    var title: String = "",
    var author: String? = null,
    var description: String? = null,
    /** Length in seconds. */
    var duration: Long = 0L,
    var thumbnailUrl: String? = null,
    var isLive: Boolean = false,
) {
    fun copyFrom(other: Metadata) {
        id = other.id
        title = other.title
        author = other.author
        description = other.description
        duration = other.duration
        thumbnailUrl = other.thumbnailUrl
        isLive = other.isLive
    }
}

@Serializable
data class Manifest(
    val url: String,
    val protocol: MediaProtocol,
    @Transient val requestPlan: MediaRequestPlan? = null,
    val expiresAtMillis: Long = Long.MAX_VALUE,
)

@Serializable
class Stream(
    var formats: List<Format> = emptyList(),
    var subtitles: List<Subtitle> = emptyList(),
    var dashUrl: String? = null,
    var hlsUrl: String? = null,
    @Transient var dashRequestPlan: MediaRequestPlan? = null,
    @Transient var hlsRequestPlan: MediaRequestPlan? = null,
    @Transient var manifests: List<Manifest> = emptyList(),
    /** Playback stats endpoints from the same successful player response; never persisted. */
    @Transient var tracking: PlayerTracking? = null,
) {
    fun copyFrom(other: Stream) {
        formats = other.formats
        subtitles = other.subtitles
        dashUrl = other.dashUrl
        hlsUrl = other.hlsUrl
        dashRequestPlan = other.dashRequestPlan
        hlsRequestPlan = other.hlsRequestPlan
        manifests = other.manifests
        tracking = other.tracking
    }

    /** Keep the complete source context for an already extracted fallback, without another API call. */
    fun excluding(client: StreamClient): Stream = Stream().also { result ->
        result.copyFrom(this)
        result.formats = formats.filter { it.requestPlan != null && it.requestPlan.client != client }
        result.manifests = manifests.filter { it.requestPlan?.client != client }
        val dash = result.manifests.firstOrNull { it.protocol == MediaProtocol.DASH }
        val hls = result.manifests.firstOrNull { it.protocol == MediaProtocol.HLS }
        result.dashUrl = dash?.url; result.dashRequestPlan = dash?.requestPlan
        result.hlsUrl = hls?.url; result.hlsRequestPlan = hls?.requestPlan
    }
}

@Serializable
class ChapterList(
    var chapters: List<Chapter> = emptyList(),
) {
    fun copyFrom(other: ChapterList) {
        chapters = other.chapters
    }
}

class Extraction(
    val metadata: Promise<Metadata>,
    val stream: Promise<Stream>,
    val chapters: Promise<ChapterList>,
)
