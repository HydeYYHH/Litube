private sealed interface SubtitlePick {
    data class Language(val key: String) : SubtitlePick
    data object Style : SubtitlePick
}

@Composable
fun PlayerAnchorDropdown(
    menu: PlayerAnchorMenu?,
    state: PlayerUiState,
    positionState: State<Long>,
    callbacks: PlayerSurfaceCallbacks,
    onDismiss: () -> Unit,
    onSubtitleStyle: () -> Unit = {},
) {
    when (menu) {
        PlayerAnchorMenu.Subtitles -> {
            // No "off" row: tapping the active language turns captions off. Style sits under the list.
            OptionDropdown(
                rows = if (state.subtitleTracks.isEmpty()) {
                    listOf(OptionRow(null, stringResource(R.string.no_subtitles), enabled = false))
                } else {
                    state.subtitleTracks.map { track ->
                        val lang = PlayerUi.languageLabel(track.language)
                        val label = if (track.autoGenerated) {
                            "$lang ${stringResource(R.string.subtitle_auto_generated)}"
                        } else {
                            lang
                        }
                        OptionRow(SubtitlePick.Language(track.key), label)
                    }
                },
                selected = if (state.subtitleEnabled) {
                    state.subtitleKey?.let { SubtitlePick.Language(it) }
                } else {
                    null
                },
                onPick = { pick ->
                    when (pick) {
                        is SubtitlePick.Language -> callbacks.onSubtitle(pick.key)
                        SubtitlePick.Style -> onSubtitleStyle()
                        null -> Unit
                    }
                    onDismiss()
                },
                onDismiss = onDismiss,
                footer = OptionRow(SubtitlePick.Style, stringResource(R.string.subtitle_style)),
            )
        }
        null -> Unit
    }
}

@Composable
private fun <T> OptionDropdown(
    rows: List<OptionRow<T>>,
    selected: T?,
    onPick: (T?) -> Unit,
    onDismiss: () -> Unit,
    footer: OptionRow<T>? = null,
) {
    val menuWidth = popupMenuWidth(rows.map { it.label } + listOfNotNull(footer?.label))
    ListPopup(onDismiss = onDismiss, width = menuWidth) {
        rows.forEach { row ->
            val isSelected = row.value == selected
            Row(
                modifier = Modifier
                    .width(menuWidth)
                    .clickable(enabled = row.enabled) { onPick(row.value) }
                    .padding(horizontal = 16.dp, vertical = 10.dp),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Text(
                    text = row.label,
                    modifier = Modifier.fillMaxWidth(),
                    fontSize = SettingsTokens.BodySize.sp,
                    fontWeight = FontWeight.Normal,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                    color = when {
                        !row.enabled -> MaterialTheme.colorScheme.onSurfaceVariant.copy(alpha = 0.5f)
                        isSelected -> MaterialTheme.colorScheme.primary
                        else -> MaterialTheme.colorScheme.onSurfaceVariant
                    },
                )
            }
        }
        footer?.let { extra ->
            HorizontalDivider(color = MaterialTheme.colorScheme.outline.copy(alpha = 0.5f))
            Row(
                modifier = Modifier
                    .width(menuWidth)
                    .clickable { onPick(extra.value) }
                    .padding(horizontal = 16.dp, vertical = 10.dp),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Text(
                    text = extra.label,
                    modifier = Modifier.fillMaxWidth(),
                    fontSize = SettingsTokens.BodySize.sp,
                    maxLines = 1,
                    overflow = TextOverflow.Ellipsis,
                    color = MaterialTheme.colorScheme.onSurface,
                )
            }
        }
    }
}

@Composable
internal fun SegmentPreviewDialog(
    title: String,
    timeLabel: String,
    thumbnailUrl: String?,
    onJump: () -> Unit,
    onDismiss: () -> Unit,
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        containerColor = AppStyle.Panel,
        text = {
            Column {
                Column(Modifier.weight(1f, fill = false).verticalScroll(rememberScrollState())) {
                    YoutubeThumb(
                        url = thumbnailUrl,
                        modifier = Modifier
                            .fillMaxWidth()
                            .height(160.dp)
                            .clip(RoundedCornerShape(8.dp)),
                        contentDescription = stringResource(R.string.thumbnail),
                    )
                    Text(
                        text = title,
                        modifier = Modifier.padding(top = 12.dp),
                        color = MaterialTheme.colorScheme.onSurface,
                        fontSize = SettingsTokens.TitleSize.sp,
                        fontWeight = FontWeight.Medium,
                    )
                }
                Text(
                    text = timeLabel,
                    modifier = Modifier.padding(top = 4.dp),
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    fontSize = SettingsTokens.BodySize.sp,
                )
            }
        },
        confirmButton = {
            TextButton(onClick = onJump) {
                Text(stringResource(R.string.jump))
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text(stringResource(R.string.close))
            }
        },
    )
}

private const val MEASURE_SAMPLE_CAP = 48

private const val MEASURE_SAMPLE = 24

/** Measured label widths memoized (bounded LRU) so reopening or 4 Hz recomposition never re-measures text on the main thread. */
private val labelWidthCache = object : LinkedHashMap<String, Int>(64, 0.75f, true) {
    override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, Int>): Boolean =
        size > 128
}

@Composable
private fun popupMenuWidth(labels: List<String>): Dp {
    val density = LocalDensity.current
    val screenPx = with(density) { LocalConfiguration.current.screenWidthDp.dp.toPx() }
    // 16 dp horizontal padding × 2, plus slack so measurement cannot undershoot.
    val padPx = with(density) { 40.dp.toPx() }
    val measurer = rememberTextMeasurer()
    val style = TextStyle(fontSize = SettingsTokens.BodySize.sp, fontWeight = FontWeight.Normal)
    val contentPx = remember(labels) {
        // Measuring every label janks first paint on videos with 100+ chapters; within
        // one text style, character count is a safe proxy for width, so sampling the
        // longest few bounds the menu width with the same practical result.
        val candidates = if (labels.size <= MEASURE_SAMPLE_CAP) {
            labels
        } else {
            labels.sortedByDescending { it.length }.take(MEASURE_SAMPLE)
        }
        candidates.maxOfOrNull { label ->
            labelWidthCache.getOrPut(label) {
                measurer.measure(text = label, style = style, maxLines = 1).size.width
            }
        } ?: 0
    }
    val menuPx = MiniPlayerLayout.popupWidthPx(contentPx + padPx.toInt(), screenPx.toInt())
    return with(density) { menuPx.toDp() }
}

@Composable
private fun ListPopup(
    onDismiss: () -> Unit,
    width: Dp,
    content: @Composable ColumnScope.() -> Unit,
) {
    val maxHeight = (LocalConfiguration.current.screenHeightDp * 0.7f).dp
    Popup(
        popupPositionProvider = BelowAnchorPositionProvider,
        onDismissRequest = onDismiss,
        properties = PopupProperties(
            focusable = true,
            clippingEnabled = false,
        ),
    ) {
        Surface(
            modifier = Modifier.requiredWidth(width),
            shape = RoundedCornerShape(12.dp),
            color = AppStyle.Panel,
            tonalElevation = 0.dp,
            shadowElevation = 4.dp,
        ) {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .heightIn(max = maxHeight)
                    .verticalScroll(rememberScrollState()),
                content = content,
            )
        }
    }
}

private object BelowAnchorPositionProvider : PopupPositionProvider {
    override fun calculatePosition(
        anchorBounds: IntRect,
        windowSize: IntSize,
        layoutDirection: LayoutDirection,
        popupContentSize: IntSize,
    ): IntOffset {
        val maxX = (windowSize.width - popupContentSize.width).coerceAtLeast(0)
        val x = if (layoutDirection == LayoutDirection.Ltr) {
            anchorBounds.left.coerceIn(0, maxX)
        } else {
            (anchorBounds.right - popupContentSize.width).coerceIn(0, maxX)
        }
        val y = if (anchorBounds.bottom + popupContentSize.height <= windowSize.height) {
            anchorBounds.bottom
        } else {
            (anchorBounds.top - popupContentSize.height).coerceAtLeast(0)
        }
        return IntOffset(x, y)
    }
}
